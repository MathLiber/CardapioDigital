CREATE DATABASE IF NOT EXISTS CARDAPIO;
USE CARDAPIO;

CREATE TABLE IF NOT EXISTS PRATO_PRINCIPAL (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    QNT INT
);

CREATE TABLE IF NOT EXISTS BEBIDA (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    QNT INT
);

CREATE TABLE IF NOT EXISTS FRUTA (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    QNT INT
);

CREATE TABLE IF NOT EXISTS CARDAPIO (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    PRATO_ID INT,
    BEBIDA_ID INT,
    FRUTA_ID INT,
    FOREIGN KEY (PRATO_ID) REFERENCES PRATO_PRINCIPAL(ID),
    FOREIGN KEY (BEBIDA_ID) REFERENCES BEBIDA(ID),
    FOREIGN KEY (FRUTA_ID) REFERENCES FRUTA(ID)
);
